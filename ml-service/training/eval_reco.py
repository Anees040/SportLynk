def _arm_table(cohort: Cohort) -> str:
    head = (
        "| arm | HitRate@5 | Precision@5 | HitRate@3 | MRR | users |\n"
        "|---|---|---|---|---|---|"
    )
    rows = []
    for key in ARM_ORDER:
        a = cohort.arms.get(key)
        if a is None:
            continue
        bold = "**" if key == ARM_CONTENT else ""
        rows.append(
            f"| {ARM_LABELS[key]} | {bold}{a.hit_rate_at_5:.3f}{bold} | {a.precision_at_5:.3f} "
            f"| {a.hit_rate_at_3:.3f} | {a.mrr:.3f} | {a.n} |"
        )
    return head + "\n" + "\n".join(rows)


def _lift_line(cohort: Cohort) -> str:
    return (
        f"**Lift on HitRate@5:** {cohort.lift(ARM_CONTENT, ARM_POPULARITY) * 100:+.1f}% over popularity  ·  "
        f"{cohort.lift(ARM_CONTENT, ARM_COLD) * 100:+.1f}% over cold-start-as-served  ·  "
        f"{cohort.lift(ARM_CONTENT, ARM_RANDOM) * 100:+.1f}% over random"
    )


def _spread_table(cohort: Cohort) -> str:
    s = cohort.match_pcts and spread(cohort.match_pcts) or {"count": 0}
    if not s.get("count"):
        return "_no percentages recorded_"
    return (
        "| min | p10 | median | p90 | max | distinct values | percentages sampled |\n"
        "|---|---|---|---|---|---|---|\n"
        f"| {s['min']}% | {s['p10']}% | {s['median']}% | {s['p90']}% | {s['max']}% "
        f"| {s['distinctValues']} | {s['count']} |"
    )


def _sweep_table(rows: list[dict]) -> str:
    head = "| history | stated | affinity | HitRate@5 | MRR |\n|---|---|---|---|---|"
    out = []
    for r in rows:
        w = r["weights"]
        mark = "  ← **shipped**" if r["shipped"] else ""
        out.append(
            f"| {w['history']:.2f} | {w['stated']:.2f} | {w['affinity']:.2f} "
            f"| {r['hitRateAt5']:.3f}{mark} | {r['mrr']:.3f} |"
        )
    return head + "\n" + "\n".join(out)

def _sweep_verdict(rows: list[dict]) -> str:
    """State what the sweep actually shows — including when it does not favour the shipped row.

    A sweep table is only evidence if the rows are separable. With ~90 held-out players the
    binomial standard error on HitRate@5 is around 5 points, which is wider than this whole
    grid; saying "0.5/0.3/0.2 won" would be reading noise. So the verdict is computed, and
    it says so when the shipped blend is merely tied.
    """
    if not rows:
        return "_sweep skipped (`--no-sweep`)_"
    shipped = next((r for r in rows if r["shipped"]), rows[0])
    best = max(rows, key=lambda r: (r["hitRateAt5"], r["mrr"]))
    n = max(shipped["n"], 1)
    p = shipped["hitRateAt5"]
    se = (p * (1.0 - p) / n) ** 0.5
    gap = best["hitRateAt5"] - shipped["hitRateAt5"]
    span = max(r["hitRateAt5"] for r in rows) - min(r["hitRateAt5"] for r in rows)
    bw = best["weights"]
    verdict = (
        f"The grid spans {span:.3f} on HitRate@5 over n = {n} held-out players, where one player is "
        f"{100.0 / n:.1f} points and the binomial standard error at p = {p:.3f} is +/-{se:.3f} "
        f"({se * 100:.1f} points). **Every row therefore sits inside one standard error of every "
        f"other one.** The finding is that the model is insensitive to this blend at this sample "
        f"size — not that the shipped split is optimal.\n\n"
    )
    if gap > se:
        verdict += (
            f"The best row ({bw['history']:.2f}/{bw['stated']:.2f}/{bw['affinity']:.2f}, "
            f"{best['hitRateAt5']:.3f}) beats the shipped one by {gap:.3f}, which does exceed the "
            f"standard error — worth re-testing on a larger population before shipping it.\n\n"
        )
    elif gap > 0:
        verdict += (
            f"The nominal best row ({bw['history']:.2f}/{bw['stated']:.2f}/{bw['affinity']:.2f}, "
            f"{best['hitRateAt5']:.3f}) is {gap:.3f} ahead — inside the noise, so it is not a reason "
            f"to change anything.\n\n"
        )
    return verdict + (
        "So why keep history at the front? Because history is the only block that separates two "
        "players who ticked the same sport, and a rail that is identical for everyone who plays "
        "cricket is not a recommendation. The sweep is what should decide this, and it cannot yet; "
        "re-run it once the real corpus has enough evaluable players to separate the rows, and ship "
        "the winner if the ordering survives."
    )


