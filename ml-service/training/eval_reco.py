CSV_COLUMNS = ("venue_id", "sport", "city", "venue_rating", "base_price", "ground_type", "slot_date", "booked")


@dataclass
class World:
    """The S.3 world reshaped into the recommender's own input contract."""

    venues: list[dict]
    dates_by_venue: dict[str, list[str]]
    venues_by_city: dict[str, list[dict]]
    as_of: str
    csv_sha256: str
    rows: int
    booked_rows: int


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1048576), b""):
            h.update(chunk)
    return h.hexdigest()

def load_world(csv_path: Path) -> World:
    """Distinct venues + observed demand + real booking dates, from booked slots only.

    `bookingCount` is the venue's ACTUAL booked-slot count in the simulated year, which
    is what makes the popularity baseline a genuine competitor rather than a formality.
    Attributes absent from the CSV stay absent (see the report's Limitations): there are
    no amenities and no street addresses in the simulated world, so `zone_of(None, city)`
    resolves to a city-level token like `ISLAMABAD:*` and the amenity block is inert.
    Fabricating either would be inventing evidence, which is worse than a narrower test.
    """
    attrs: dict[str, dict] = {}
    booked_by_venue: dict[str, int] = defaultdict(int)
    dates_by_venue: dict[str, list[str]] = defaultdict(list)
    total = 0
    booked_total = 0
    with csv_path.open(encoding="utf-8", newline="") as fh:
        for row in csv.DictReader(fh):
            total += 1
            vid = row["venue_id"]
            if vid not in attrs:
                attrs[vid] = {k: row.get(k) for k in CSV_COLUMNS}
            if row.get("booked") == "1":
                booked_total += 1
                booked_by_venue[vid] += 1
                dates_by_venue[vid].append(row["slot_date"])

    venues: list[dict] = []
    for vid, row in attrs.items():
        rating = row.get("venue_rating") or ""
        venues.append(
            {
                "venueId": vid,
                "name": "Synthetic " + vid,
                "city": row.get("city"),
                "sportType": row.get("sport"),
                # A blank venue_rating in the CSV is a real unrated venue — pass None, do
                # not substitute a mean, so the rating block's absent path is exercised.
                "rating": float(rating) if rating else None,
                "pricePerHour": float(row.get("base_price") or 0) or None,
                "groundType": row.get("ground_type"),
                "bookingCount": booked_by_venue.get(vid, 0),
                "isActive": True,
                # address / amenities / totalReviews genuinely do not exist in this world.
            }
        )

    all_dates = [d for ds in dates_by_venue.values() for d in ds]
    anchor = max(all_dates) if all_dates else "2026-01-01"
    as_of = (datetime.fromisoformat(anchor) + timedelta(days=1)).replace(tzinfo=timezone.utc).isoformat()

    by_city: dict[str, list[dict]] = defaultdict(list)
    for v in venues:
        by_city[str(v["city"])].append(v)

    return World(
        venues=venues,
        dates_by_venue=dict(dates_by_venue),
        venues_by_city=dict(by_city),
        as_of=as_of,
        csv_sha256=_sha256_file(csv_path),
        rows=total,
        booked_rows=booked_total,
    )

# The user layer the simulator never had


def _pmf(mapping: dict) -> tuple[list, np.ndarray]:
    keys = list(mapping.keys())
    p = np.asarray([float(mapping[k]) for k in keys], dtype=float)
    return keys, p / p.sum()


def _price_affinity(price, target: float, tolerance: float) -> float:
    """1.0 at the player's target price, decaying in LOG price — a player who books
    2,000-rupee pitches is roughly as unlikely to book 1,000 as 4,000."""
    value = float(price or 0)
    if value <= 0 or target <= 0:
        return 0.0
    return float(np.exp(-abs(np.log(value / target)) / tolerance))

def simulate_users(world: World, rng: np.random.Generator, cfg: dict) -> list[dict]:
    """Draw players with a latent taste and sample their booking sequences.

    Each player books ONLY in their home city, which is both realistic and the reason
    the zone block carries any signal in this world. Repeat visits are allowed: a player
    who likes one pitch books it again, and suppressing that would remove the single most
    common pattern in a real bookings table (and quietly make the task easier).
    """
    cities, city_p = _pmf(
        {c: sum(v["bookingCount"] for v in vs) or 1 for c, vs in world.venues_by_city.items()}
    )
    n_keys, n_p = _pmf(cfg["bookingsPmf"])
    taste = cfg["taste"]
    users: list[dict] = []

    for i in range(int(cfg["synthUsers"])):
        city = str(cities[int(rng.choice(len(cities), p=city_p))])
        pool = [v for v in world.venues_by_city[city] if world.dates_by_venue.get(v["venueId"])]
        if not pool:
            continue

        sports = sorted({str(v["sportType"]) for v in pool})
        demand = np.asarray([float(v["bookingCount"]) for v in pool])
        primary = str(sports[int(rng.integers(len(sports)))])
        secondary = None
        if len(sports) > 1 and rng.random() < cfg["secondarySportProb"]:
            secondary = str(next(s for s in sports if s != primary))

        prices = [float(v["pricePerHour"]) for v in pool if v.get("pricePerHour")]
        target_price = float(prices[int(rng.integers(len(prices)))]) if prices else 2000.0
        rating_taste = float(rng.random())

        utility = []
        for v in pool:
            sport = str(v["sportType"])
            sport_fit = 1.0 if sport == primary else (0.6 if sport == secondary else 0.05)
            rating_fit = (float(v["rating"]) / 5.0) if v.get("rating") else 0.5
            utility.append(
                taste["sport"] * sport_fit
                + taste["price"] * _price_affinity(v.get("pricePerHour"), target_price, cfg["priceTolerance"])
                + taste["rating"] * (rating_taste * rating_fit + (1.0 - rating_taste) * 0.5)
                + taste["demand"] * (float(v["bookingCount"]) / max(float(demand.max()), 1.0))
            )
        w = np.asarray(utility, dtype=float) ** float(cfg["tasteSharpness"])
        w = w / w.sum()

        n_bookings = int(n_keys[int(rng.choice(len(n_keys), p=n_p))])
        bookings = []
        for _ in range(n_bookings):
            v = pool[int(rng.choice(len(pool), p=w))]
            dates = world.dates_by_venue[v["venueId"]]
            bookings.append({"venueId": v["venueId"], "bookedAt": dates[int(rng.integers(len(dates)))]})
        bookings.sort(key=lambda b: b["bookedAt"])

        stated = []
        if rng.random() < cfg["statedSportProb"]:
            stated = [primary] + ([secondary] if secondary else [])
        high_reviews = []
        if bookings and rng.random() < cfg["highReviewProb"]:
            high_reviews = [{"venueId": bookings[int(rng.integers(len(bookings)))]["venueId"]}]

        users.append(
            {
                "userId": "synth-%04d" % i,
                # Blank on purpose — see rank_arms(): the hard city prefilter is disabled
                # for all arms so every arm competes over one candidate set.
                "city": "",
                "homeCity": city,
                "sportPreferences": stated,
                "bookings": bookings,
                "highReviews": high_reviews,
            }
        )
    return users

# Metrics


@dataclass
class Arm:
    """One ranking strategy's tally over a cohort of held-out users."""

    name: str
    n: int = 0
    hits3: int = 0
    hits5: int = 0
    rr: float = 0.0

    def record(self, ranked: list[str], held: str) -> None:
        self.n += 1
        if held in ranked[:3]:
            self.hits3 += 1
        if held in ranked[:5]:
            self.hits5 += 1
        if held in ranked:
            self.rr += 1.0 / (ranked.index(held) + 1)

    @property
    def hit_rate_at_3(self) -> float:
        return self.hits3 / self.n if self.n else 0.0

    @property
    def hit_rate_at_5(self) -> float:
        return self.hits5 / self.n if self.n else 0.0

    @property
    def precision_at_5(self) -> float:
        """HitRate@5 / 5, exactly — and that is not a bug.

        Leave-last-out hides ONE venue, so a top-5 list can contain at most one relevant
        item and Precision@5 is a mechanical restatement of HitRate@5. It is reported
        because the wave asks for it, and the identity is stated in the report rather than
        dressed up as independent evidence. MRR is the metric that adds information here.
        """
        return self.hit_rate_at_5 / EVAL_CONFIG["topK"]

    @property
    def mrr(self) -> float:
        return self.rr / self.n if self.n else 0.0

    def as_dict(self) -> dict:
        return {
            "n": self.n,
            "hitRateAt3": round(self.hit_rate_at_3, 6),
            "hitRateAt5": round(self.hit_rate_at_5, 6),
            "precisionAt5": round(self.precision_at_5, 6),
            "mrr": round(self.mrr, 6),
        }


@dataclass
class Cohort:
    """The four arms measured over one slice of eligible users."""

    label: str
    detail: str
    arms: dict[str, Arm] = field(default_factory=dict)
    match_pcts: list[int] = field(default_factory=list)

    def arm(self, key: str) -> Arm:
        return self.arms.setdefault(key, Arm(key))

    def lift(self, key: str, over: str) -> float:
        """Relative gain in HitRate@5. 0.0 when either arm is empty — a cohort can be."""
        a, b = self.arms.get(key), self.arms.get(over)
        if a is None or b is None or b.hit_rate_at_5 <= 0:
            return 0.0
        return (a.hit_rate_at_5 - b.hit_rate_at_5) / b.hit_rate_at_5

    def as_dict(self) -> dict:
        return {
            "label": self.label,
            "detail": self.detail,
            "arms": {k: a.as_dict() for k, a in self.arms.items()},
            "liftOverPopularity": round(self.lift(ARM_CONTENT, ARM_POPULARITY), 6),
            "liftOverColdStart": round(self.lift(ARM_CONTENT, ARM_COLD), 6),
            "matchPctSpread": spread(self.match_pcts),
        }


def spread(values: list[int]) -> dict:
    """Distribution of the match percentages the model would actually print.

    The wave's fourth pitfall is a wall of 97-99% looking fake to a committee. The
    defence is not an assurance, it is this five-number summary of every percentage the
    top-5 rails would have shown across the whole evaluated population.
    """
    if not values:
        return {"count": 0}
    ordered = sorted(values)
    return {
        "count": len(ordered),
        "min": ordered[0],
        "p10": ordered[int(0.10 * (len(ordered) - 1))],
        "median": int(statistics.median(ordered)),
        "p90": ordered[int(0.90 * (len(ordered) - 1))],
        "max": ordered[-1],
        "distinctValues": len(set(ordered)),
    }

# The four arms


def _strip(user: dict, *, keep_sports: bool) -> dict:
    """A profile with the personal signal removed — the baselines' input.

    `keep_sports=True` is COLD-START AS SERVED: what a brand-new account really sees
    (popularity blended with whatever sports they ticked at signup). `False` is pure
    popularity, the wave's named baseline.
    """
    return {
        **user,
        "bookings": [],
        "highReviews": [],
        "sportPreferences": user.get("sportPreferences", []) if keep_sports else [],
    }


def _trim(user: dict) -> tuple[dict, str] | None:
    """Hide the most recent booking. Returns (trimmed user, held-out venue id).

    The high-review list is filtered against the held-out venue as well. Leaving it
    would leak the answer through the affinity block — a 5-star review on the very venue
    being predicted — and inflate the content arm for free.
    """
    bookings = user.get("bookings") or []
    if len(bookings) < EVAL_CONFIG["minBookings"]:
        return None
    held = str(bookings[-1].get("venueId") or bookings[-1].get("venue_id"))
    keep = [
        r
        for r in (user.get("highReviews") or user.get("high_reviews") or [])
        if str(r.get("venueId") or r.get("venue_id")) != held
    ]
    return {**user, "bookings": bookings[:-1], "highReviews": keep}, held


def evaluate(
    venues: list[dict],
    users: list[dict],
    *,
    as_of: str,
    rng: np.random.Generator,
    label: str,
    detail: str,
) -> tuple[Cohort, Cohort, dict]:
    """Leave-last-out over four arms, split into an all-items and a novel-venue cohort.

    One recommender is fitted per arm over ALL trimmed users at once, which is both far
    cheaper than one instance per user and closer to the serving path — the model has no
    collaborative term, so a user's ranking cannot be influenced by another user's rows.
    """
    trimmed: list[tuple[dict, str]] = []
    for u in users:
        got = _trim(u)
        if got:
            trimmed.append(got)

    content_model = VenueRecommender(venues, [t for t, _ in trimmed], as_of=as_of)
    pop_model = VenueRecommender(venues, [_strip(t, keep_sports=False) for t, _ in trimmed], as_of=as_of)
    cold_model = VenueRecommender(venues, [_strip(t, keep_sports=True) for t, _ in trimmed], as_of=as_of)
    depth = max(EVAL_CONFIG["topK"], len(venues))
    all_ids = [str(v.get("venueId") or v.get("id")) for v in venues]

    every = Cohort(label, detail)
    novel = Cohort(label + " · novel venues only", "held-out venue absent from the trimmed history")

    for user, held in trimmed:
        uid = str(user.get("userId") or user.get("user_id"))
        seen = {str(b.get("venueId") or b.get("venue_id")) for b in user["bookings"]}
        items = content_model.recommend(uid, limit=depth)["items"]
        ranked = {
            ARM_CONTENT: [x["venue_id"] for x in items],
            ARM_POPULARITY: [x["venue_id"] for x in pop_model.recommend(uid, limit=depth)["items"]],
            ARM_COLD: [x["venue_id"] for x in cold_model.recommend(uid, limit=depth)["items"]],
            # A fresh permutation per user, from the seeded generator: the floor any
            # ranking has to clear, and the only arm with no score to publish.
            ARM_RANDOM: [all_ids[i] for i in rng.permutation(len(all_ids))],
        }
        pcts = [int(x["match_pct"]) for x in items[: EVAL_CONFIG["topK"]]]
        for cohort in (every,) if held in seen else (every, novel):
            for key, order in ranked.items():
                cohort.arm(key).record(order, held)
            cohort.match_pcts.extend(pcts)

    # Pitfall 3: a user with no history and no stated sport must reach the popularity
    # branch, not a cosine against a zero vector. Verified on the real population rather
    # than asserted in a comment.
    blank = [u for u in users if not (u.get("bookings") or u.get("highReviews") or u.get("sportPreferences"))]
    guard = {"zeroSignalUsers": len(blank), "coldStartOk": True, "profiles": []}
    probe = VenueRecommender(venues, blank[:25], as_of=as_of)
    for u in blank[:25]:
        out = probe.recommend(str(u.get("userId") or u.get("user_id")), limit=EVAL_CONFIG["topK"])
        guard["profiles"].append(out["profile"])
        if out["profile"] != rf.PROFILE_COLD_START or not out["items"]:
            guard["coldStartOk"] = False
    guard["profiles"] = sorted(set(guard["profiles"]))
    return every, novel, guard

# "Why 0.5 / 0.3 / 0.2?" — the sweep that answers it with a table


def sweep(venues: list[dict], users: list[dict], *, as_of: str, seed: int) -> list[dict]:
    """Re-measure the content arm under alternative user-vector blends.

    core/reco_features.py is FROZEN — its fingerprint is stamped inside the released
    artifact, so editing it would orphan the model. The sweep therefore rebinds the
    weight dict in memory and restores it in a finally block; the file on disk is never
    touched. Each row is the same leave-last-out test on the same seeded population, so
    the only thing varying is the blend.
    """
    original = rf.COMPONENT_WEIGHTS
    out: list[dict] = []
    try:
        for weights in WEIGHT_GRID:
            rf.COMPONENT_WEIGHTS = dict(weights)
            _, novel, _ = evaluate(
                venues,
                users,
                as_of=as_of,
                rng=np.random.default_rng(seed),
                label="sweep",
                detail="",
            )
            arm = novel.arms[ARM_CONTENT]
            out.append(
                {
                    "weights": dict(weights),
                    "shipped": all(
                        abs(weights[k] - SHIPPED_WEIGHTS[k]) < 1e-9 for k in SHIPPED_WEIGHTS
                    ),
                    "hitRateAt5": round(arm.hit_rate_at_5, 6),
                    "mrr": round(arm.mrr, 6),
                    "n": arm.n,
                }
            )
    finally:
        rf.COMPONENT_WEIGHTS = original
    return out


# The real seeded corpus — read from the released artifact, not from Postgres


def load_artifact(path: Path) -> dict:
    if not path.exists():
        raise SystemExit(
            f"{path} not found.\n"
            "  -> train first:  .\\.venv\\Scripts\\python.exe training\\build_reco.py"
        )
    artifact = joblib.load(path)
    if not isinstance(artifact, dict) or not isinstance(artifact.get("model"), VenueRecommender):
        raise SystemExit(f"{path} does not hold a VenueRecommender artifact")
    return artifact


def eligible_count(users: list[dict], minimum: int) -> int:
    return sum(1 for u in users if len(u.get("bookings") or []) >= minimum)

