r"""
Offline evaluation of SportLynk model #3 — the venue recommender (S.5 Wave C).

THE QUESTION THIS SCRIPT ANSWERS
  "How do you know it works?" — with a leave-last-out ranking test against three
  baselines, on a population large enough for the numbers to mean something.

WHY THIS SCRIPT EXISTS SEPARATELY FROM build_reco.py
  build_reco.py TRAINS: it needs the Node backend up, the export key, and the live
  database, and its leave-one-out ran over the seed snapshot — which had 2 evaluable
  users. Two users is a direction, not a measurement: one user flips HitRate@5 by 50
  points. This script EVALUATES, needs no backend and no database, and gets its
  statistical power from the S.3 synthetic world instead. It reads:

    1. models/reco_latest.joblib  — the RELEASED artifact, so the thing measured is
       the thing served (the frozen catalogue AND the frozen real-user snapshot).
    2. data/bookings_synth.csv    — the S.3 simulator's world, hash-verified and NEVER
       regenerated here (a new CSV = a new sha256 = a broken provenance gate).

  Run order for a full refresh is therefore: build_reco.py (train) -> eval_reco.py
  (measure + write the card). This script owns reports/reco_eval.md and
  reports/model_card_reco.md; build_reco.py writes a thinner version of both at train
  time, so re-run this after any retrain or the card will understate the evidence.

THE SYNTHETIC POPULATION, AND WHY IT IS NOT A RIGGED TEST
  The CSV is SLOT-level (venue x slot x booked), with no user column — the S.3
  simulator modelled demand, not identity. So this script adds the missing layer: it
  draws users with a latent taste (home city, primary sport, target price, rating
  sensitivity) and samples each booking from the CSV's OWN booked rows in proportion
  to that taste times the venue's real observed demand. Venue attributes, per-venue
  popularity and booking dates all come from the frozen world; only the user layer is
  new, and its generative process is printed in the report.

  The obvious objection is circularity: if users were generated by the same features
  the model scores, of course the model wins. Three things answer it, and all three
  are in the published table:
    * POPULARITY is a real competitor here, not a straw man — taste includes the
      venue's observed demand, so the crowd-favourite venue genuinely is a decent
      guess for everyone.
    * COLD-START AS SERVED (popularity + stated sports) is reported as a fourth arm.
      It is the strongest baseline and the one the app actually falls back to, so the
      honest lift claim is measured against IT, not against random.
    * The NOVEL-VENUE cohort excludes every case where the held-out venue already
      appears in the trimmed history. Repeat visits are trivially recoverable (the
      venue sits next to its own profile vector), so the headline number is the
      cohort where the model must generalise to a venue the user has never booked.

  Taste weights live in EVAL_CONFIG below and are the SIMULATOR's, not the model's.
  The model's own blend weights are swept separately (see WEIGHT_GRID) so "why 0.5
  history / 0.3 stated / 0.2 affinity?" has a table behind it rather than an opinion.
  The sweep patches the weight dict IN MEMORY for the duration of the sweep and
  restores it; core/reco_features.py is never edited and its fingerprint stays
  138790ba577ea0f0, which is what keeps the released artifact loadable.

RUN IT
  cd ml-service
  .\.venv\Scripts\python.exe training\eval_reco.py
  .\.venv\Scripts\python.exe training\eval_reco.py --no-write   # print only
"""
